CREATE TABLE users (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         VARCHAR2(255) NOT NULL UNIQUE,
  password_hash VARCHAR2(100) NOT NULL,
  created_at    TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE buckets (
  id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        NUMBER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name           VARCHAR2(100) NOT NULL,
  versioning     NUMBER(1) DEFAULT 1,
  lifecycle_days NUMBER,
  created_at     TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE objects (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bucket_id  NUMBER NOT NULL REFERENCES buckets(id) ON DELETE CASCADE,
  obj_key    VARCHAR2(255) NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT uq_bucket_key UNIQUE (bucket_id, obj_key)
);

CREATE TABLE versions (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  object_id   NUMBER NOT NULL REFERENCES objects(id) ON DELETE CASCADE,
  version_no  NUMBER NOT NULL,
  path        VARCHAR2(500) NOT NULL,
  size_bytes  NUMBER,
  mime        VARCHAR2(100),
  sha256      VARCHAR2(64),
  uploaded_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE shares (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version_id NUMBER NOT NULL REFERENCES versions(id) ON DELETE CASCADE,
  recipient  VARCHAR2(255) NOT NULL,
  max_views  NUMBER NOT NULL,
  view_count NUMBER DEFAULT 0,
  expires_at NUMBER NOT NULL,
  revoked    NUMBER(1) DEFAULT 0,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE audit_log (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts         VARCHAR2(40)  NOT NULL,
  actor      VARCHAR2(255) NOT NULL,
  action     VARCHAR2(50)  NOT NULL,
  target     VARCHAR2(255) NOT NULL,
  details    VARCHAR2(500) NOT NULL,
  prev_hash  VARCHAR2(64)  NOT NULL,
  entry_hash VARCHAR2(64)  NOT NULL
);